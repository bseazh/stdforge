function bindSyncedScroll() {
  const zhBlock = elements.segmentList.querySelector('[data-lang="zh"]');
  const enBlock = elements.segmentList.querySelector('[data-lang="en"]');
  if (!zhBlock || !enBlock) return;
  let syncing = false;
  const sync = (source, target) => {
    if (syncing) return;
    const maxSource = source.scrollHeight - source.clientHeight;
    const maxTarget = target.scrollHeight - target.clientHeight;
    if (maxSource <= 0 || maxTarget <= 0) return;
    syncing = true;
    target.scrollTop = (source.scrollTop / maxSource) * maxTarget;
    window.requestAnimationFrame(() => { syncing = false; });
  };
  zhBlock.addEventListener('scroll', () => sync(zhBlock, enBlock));
  enBlock.addEventListener('scroll', () => sync(enBlock, zhBlock));
}

function generateTranslation(silent = false) {
  const title = elements.title.value.trim();
  const parts = splitSegments(elements.source.value);
  if (!title || !parts.length) return notify('请先填写文档标题和中文正文');
  const demoEnglishParts = isVehicleRefrigeratorDemo(title, elements.source.value) ? splitSegments(sampleEnglish) : null;
  if (translation) {
    translation.title = title;
    translation.segments = parts.map((zh, index) => ({
      id: translation.segments[index]?.id || `segment-${index + 1}`,
      zh,
      en: demoEnglishParts?.[index] || demoTranslate(zh)
    }));
    enVersion += 1;
  } else {
    translation = {
      title,
      mode,
      segments: parts.map((zh, index) => ({ id: `segment-${index + 1}`, zh, en: demoEnglishParts?.[index] || demoTranslate(zh) }))
    };
    zhVersion = 1;
    enVersion = 1;
  }
  englishStale = false;
  view = 'parallel';
  document.querySelectorAll('[data-view]').forEach(button => button.classList.toggle('selected', button.dataset.view === view));
  renderTranslation();
  if (!silent) notify('英文版本已生成，术语已按术语库优先替换');
}

